fn theme(
    id: &str,
    name: &str,
    bg: &str,
    fg: &str,
    cursor: &str,
    selection: &str,
    ansi: [&str; 16],
) -> Theme {
    Theme {
        id: id.into(),
        name: name.into(),
        is_builtin: true,
        json: json!({
            "background": bg,
            "foreground": fg,
            "cursor": cursor,
            "cursorAccent": bg,
            "selectionBackground": selection,
            "black": ansi[0],
            "red": ansi[1],
            "green": ansi[2],
            "yellow": ansi[3],
            "blue": ansi[4],
            "magenta": ansi[5],
            "cyan": ansi[6],
            "white": ansi[7],
            "brightBlack": ansi[8],
            "brightRed": ansi[9],
            "brightGreen": ansi[10],
            "brightYellow": ansi[11],
            "brightBlue": ansi[12],
            "brightMagenta": ansi[13],
            "brightCyan": ansi[14],
            "brightWhite": ansi[15],
        }),
    }
}
